import { test, expect } from '@playwright/test'
const accessKey = process.env.LEDGER_TEST_ACCESS_KEY!

test('电脑与手机共用账本：建卡、记账、退款、预算、筛选和导出', async ({ page, browser }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.getByPlaceholder('粘贴访问密钥').fill(accessKey)
  await page.getByRole('button', { name: '进入账本' }).click()
  await expect(page.getByRole('heading', { name: '月度总览.' })).toBeVisible()
  await page.goto('/cards')
  await expect(page.getByRole('heading', { name: '我的信用卡.' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: '月度总览.' })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: '我的信用卡.' })).toBeVisible()
  await page.locator('.sidebar').getByRole('button', { name: '我的信用卡' }).click()
  await page.getByRole('button', { name: '添加信用卡', exact: true }).click()
  const cardDialog = page.getByRole('dialog')
  await cardDialog.getByRole('combobox', { name: '银行名称', exact: true }).fill('招商')
  await page.getByRole('option', { name: '招商银行', exact: true }).click()
  await cardDialog.getByPlaceholder('例如：日常消费卡').fill('日常卡')
  await cardDialog.getByPlaceholder('仅需后四位，无需完整卡号').fill('0123')
  await cardDialog.getByRole('button', { name: '保存卡片' }).click()
  await expect(page.locator('.credit-card')).toContainText('0123')
  // 自定义银行可保存并在编辑时回显，也能切回内置银行。
  await page.getByRole('button', { name: '编辑信用卡', exact: true }).click()
  await cardDialog.getByRole('combobox', { name: '银行名称', exact: true }).fill('本地测试银行')
  await page.getByRole('option', { name: '本地测试银行', exact: true }).click()
  await cardDialog.getByRole('button', { name: '保存卡片' }).click()
  await expect(page.locator('.credit-card')).toContainText('本地测试银行')
  await page.getByRole('button', { name: '编辑信用卡', exact: true }).click()
  await expect(cardDialog.locator('.el-select__selected-item').filter({ hasText: /^本地测试银行$/ })).toBeVisible()
  await cardDialog.getByRole('combobox', { name: '银行名称', exact: true }).fill('招商')
  await page.getByRole('option', { name: '招商银行', exact: true }).click()
  await cardDialog.getByRole('button', { name: '保存卡片' }).click()
  await expect(page.locator('.credit-card')).toContainText('招商银行')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const phone = await mobile.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto('/')
  await phone.getByPlaceholder('粘贴访问密钥').fill(accessKey)
  await phone.getByRole('button', { name: '进入账本' }).click()
  await expect(phone.getByRole('heading', { name: '月度总览.' })).toBeVisible()
  await phone.getByRole('button', { name: '记一笔', exact: true }).click()
  await expect(phone.getByRole('group', { name: '金额数字键盘' })).toBeVisible()
  for (const key of ['1', '2', '3', '.', '4', '5', '6']) await phone.getByRole('button', { name: key === '.' ? '小数点' : `数字${key}`, exact: true }).click()
  await expect(phone.getByRole('dialog').getByPlaceholder('0.00')).toHaveValue('123.45')
  await phone.getByRole('button', { name: '完整表单', exact: true }).click()
  await expect(phone.getByRole('dialog').getByPlaceholder('0.00')).toHaveValue('123.45')
  await phone.getByRole('dialog').getByPlaceholder('例如：午餐、超市采购（可选）').fill('手机午餐记录')
  await phone.getByRole('button', { name: '保存记录' }).click()
  await expect(phone.locator('.primary-metric')).toContainText('123.45')
  await phone.getByRole('button', { name: '记一笔', exact: true }).click()
  await phone.getByRole('button', { name: '完整表单', exact: true }).click()
  await phone.getByRole('dialog').locator('.el-radio-button').filter({ hasText: '退款' }).click()
  await phone.getByRole('dialog').getByPlaceholder('0.00').fill('23.45')
  await phone.getByRole('button', { name: '保存记录' }).click()
  await expect(phone.locator('.primary-metric')).toContainText('100.00')
  await phone.locator('.mobile-nav').getByRole('button', { name: '消费明细' }).click()
  await expect(phone.locator('.mobile-record')).toHaveCount(2)
  await expect(phone.locator('.mobile-records')).toContainText('手机午餐记录')

  await page.locator('.sidebar').getByRole('button', { name: '月度总览' }).click()
  await page.getByRole('button', { name: '刷新账本' }).click()
  await expect(page.locator('.primary-metric')).toContainText('100.00')
  await page.getByRole('button', { name: '设置月度预算' }).first().click()
  await page.getByPlaceholder('例如：8000.00').fill('1000')
  await page.getByRole('button', { name: '保存预算' }).click()
  await expect(page.locator('.budget-panel')).toContainText('剩余 ¥900.00')
  await page.locator('.sidebar').getByRole('button', { name: '消费明细' }).click()
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(2)
  await page.getByRole('textbox', { name: '搜索商户或备注' }).fill('手机午餐记录')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(1)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 CSV' }).click()
  expect((await downloadPromise).suggestedFilename()).toContain('信用卡明细')
  await page.getByRole('button', { name: '删除记录', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '删除记录' })).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(1)

  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    for (const target of ['overview', 'card-statistics', 'records', 'cards']) {
      const name = { overview: '月度总览', 'card-statistics': '各卡月度统计', records: '消费明细', cards: '我的信用卡' }[target]!
      await page.locator(width < 768 ? '.mobile-nav' : '.sidebar').getByRole('button', { name }).click()
      const overflow = await page.evaluate(() => ({ width: window.innerWidth, scrollWidth: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > window.innerWidth + 1 && getComputedStyle(el).position !== 'absolute').slice(0, 15).map(el => ({ tag: el.tagName, class: el.className, right: el.getBoundingClientRect().right })) }))
      expect(overflow.scrollWidth, JSON.stringify({ width, target, ...overflow })).toBeLessThanOrEqual(overflow.width)
    }
  }
  await page.locator('.sidebar').getByRole('button', { name: '各卡月度统计' }).click()
  await expect(page.locator('.year-chart-column')).toHaveCount(12)
  await expect(page.locator('.monthly-card').first()).toContainText('123.45')
  await expect(page.locator('.monthly-card').first()).toContainText('23.45')
  await expect(page.locator('.monthly-card').first()).toContainText('100.00')
  await page.getByRole('button', { name: /查看招商银行尾号0123当月消费明细/ }).click()
  await expect(page).toHaveURL(/\/records$/)
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(2)
  await phone.reload()
  await expect(phone).toHaveURL(/\/records$/)
  await expect(phone.getByRole('heading', { name: '消费明细.' })).toBeVisible()
  await expect(phone.locator('.mobile-record')).toHaveCount(2)
  await phone.locator('.mobile-nav').getByRole('button', { name: '月度总览' }).click()
  await expect(phone.locator('.primary-metric')).toContainText('100.00')
  await phone.getByRole('button', { name: '锁定账本' }).click()
  await expect(phone.getByRole('heading', { name: '打开你的账本' })).toBeVisible()
  expect(errors).toEqual([])
  await mobile.close()
})


test('手机极简记账只输入金额和选卡即可保存，编辑仍显示完整表单', async ({ page, request }) => {
  const headers = { Authorization: `Bearer ${accessKey}` }
  const created = await request.post('/api/cards', { headers, data: { bank: '平安银行', name: '快速记账卡', last4: '9988', color: '#16665b' } })
  const { id: cardId } = await created.json()
  let recordId: number | undefined
  try {
    await page.setViewportSize({ width: 375, height: 667 })
    await page.goto('/')
    await page.getByPlaceholder('粘贴访问密钥').fill(accessKey)
    await page.getByRole('button', { name: '进入账本' }).click()
    await page.getByRole('button', { name: '记一笔', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(page.getByRole('group', { name: '金额数字键盘' })).toBeVisible()
    await expect(dialog.getByPlaceholder('例如：午餐、超市采购（可选）')).not.toBeVisible()
    await page.getByRole('group', { name: '选择记账信用卡' }).getByRole('button', { name: /平安银行 · 9988/ }).click()
    await page.getByRole('button', { name: '数字0', exact: true }).click()
    await dialog.getByRole('button', { name: '保存记录' }).click()
    await expect(dialog.getByText('请输入大于 0 的金额，最多两位小数')).toBeVisible()
    await page.getByRole('button', { name: '小数点', exact: true }).click()
    await page.getByRole('button', { name: '数字0', exact: true }).click()
    await page.getByRole('button', { name: '数字1', exact: true }).click()
    const save = dialog.getByRole('button', { name: '保存记录' })
    const box = await save.boundingBox()
    expect(box && box.y >= 0 && box.y + box.height <= 667).toBeTruthy()
    await save.click()
    await expect(dialog).not.toBeVisible()
    const now = new Date()
    const month = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`
    const response = await request.get(`/api/transactions?month=${month}&card_id=${cardId}`, { headers })
    const result = await response.json()
    expect(result.total).toBe(1)
    expect(result.rows[0]).toMatchObject({ card_id: cardId, amount_cents: 1, type: 'expense', category: '其他消费', merchant: '', note: '' })
    recordId = result.rows[0].id
    await page.getByRole('button', { name: '记一笔', exact: true }).click()
    await expect(page.getByRole('group', { name: '选择记账信用卡' }).getByRole('button', { name: /平安银行 · 9988/ })).toHaveAttribute('aria-pressed', 'true')
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await page.locator('.mobile-nav').getByRole('button', { name: '消费明细' }).click()
    const row = page.locator('.mobile-record').filter({ hasText: '平安银行 · 9988' })
    await row.getByRole('button', { name: '编辑', exact: true }).click()
    await expect(dialog.getByPlaceholder('例如：午餐、超市采购（可选）')).toBeVisible()
    await expect(page.getByRole('group', { name: '金额数字键盘' })).not.toBeVisible()
    await expect(dialog.getByPlaceholder('0.00')).toHaveValue('0.01')
  } finally {
    if (recordId) await request.delete(`/api/transactions/${recordId}`, { headers })
    await request.delete(`/api/cards/${cardId}`, { headers })
  }
})
